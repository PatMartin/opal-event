"""ZeroMQ XSUB/XPUB broker: the pure best-effort transport described in zeromq_protocol.md.

Topology
--------
- An **XSUB** socket binds ``zeromq.publishers`` (default ``tcp://127.0.0.1:5555``); external PUB
  producers connect here.
- An **XPUB** socket binds ``zeromq.subscribers`` (default ``tcp://127.0.0.1:5556``); external SUB
  consumers connect here.
- ``zmq.proxy(xsub, xpub)`` transparently forwards data frames XSUB -> XPUB and propagates
  subscription control frames XPUB -> XSUB (standard ZMQ forwarder device), which is what lets
  upstream PUB producers learn that somebody downstream wants their messages.
- A service-owned **internal observer** connects a SUB socket to the XPUB backend, subscribed to
  every topic, and is what actually feeds validation/storage/rule-matching -- for both directly
  published ZeroMQ events *and* REST-ingress events (REST publishes through a service-owned PUB
  connector into the XSUB frontend, then relies on this same observer).

CURVE
-----
When ``zeromq.curve.enabled`` is true, the XSUB/XPUB sockets run as CURVE servers using the
configured keypair, and a :class:`zmq.auth.thread.ThreadAuthenticator` authorizes external client
public keys found in ``authorized_client_keys_file`` (a directory of zmq certificate files, per
``zmq.auth`` conventions). The service's own internal connectors (REST publisher, internal
observer) are first-party, same-process components: they are issued an ephemeral keypair that is
always implicitly authorized, independent of the external allowlist.
"""

from __future__ import annotations

import contextlib
import json
import logging
import os
import queue
import shutil
import tempfile
import threading
import time
import uuid
from collections.abc import Callable
from datetime import UTC, datetime
from typing import Any

import zmq
import zmq.auth
from zmq.auth.thread import ThreadAuthenticator

from opal_event.models import ZeroMqSettings

logger = logging.getLogger("opal_event.broker")

TOPIC_MAX_LENGTH = 255


def _now() -> str:
    return datetime.now(UTC).isoformat().replace("+00:00", "Z")


def _write_public_cert(path: str, public_key: bytes) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("#   Generated by opal-event\n")
        fh.write(f'public-key = "{public_key.decode("ascii")}"\n')


class InvalidEventError(Exception):
    pass


def parse_and_normalize(topic_bytes: bytes, payload_bytes: bytes, max_event_bytes: int) -> dict[str, Any]:
    """Validates a raw two-frame ZeroMQ message and normalizes it for internal storage.

    Raises :class:`InvalidEventError` for anything the observer must reject (oversized, malformed
    JSON, topic/envelope mismatch) per zeromq_protocol.md; the pure broker proxy still forwards the
    original frames regardless, so this validation only governs the observer's own copy.
    """
    if len(topic_bytes) + len(payload_bytes) > max_event_bytes:
        raise InvalidEventError("event exceeds max_event_bytes")
    try:
        topic = topic_bytes.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise InvalidEventError("topic is not valid UTF-8") from exc
    try:
        envelope = json.loads(payload_bytes.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise InvalidEventError("payload is not valid JSON") from exc
    if not isinstance(envelope, dict) or "topic" not in envelope or "data" not in envelope:
        raise InvalidEventError("envelope missing required 'topic'/'data' keys")
    if envelope["topic"] != topic:
        raise InvalidEventError("frame topic does not match envelope topic")
    return {
        "id": envelope.get("id") or str(uuid.uuid4()),
        "topic": topic,
        "source": envelope.get("source") or "unknown",
        "timestamp": envelope.get("timestamp") or _now(),
        "data": envelope.get("data"),
    }


class Broker:
    """Owns the ZeroMQ context, proxy, internal observer, and REST publisher connector."""

    def __init__(self, settings: ZeroMqSettings, on_event: Callable[[dict[str, Any]], None]):
        self._settings = settings
        self._on_event = on_event
        self._ctx: zmq.Context | None = None
        self._xsub: zmq.Socket | None = None
        self._xpub: zmq.Socket | None = None
        self._observer_sub: zmq.Socket | None = None
        self._authenticator: ThreadAuthenticator | None = None
        self._curve_tempdir: tempfile.TemporaryDirectory | None = None
        self._proxy_thread: threading.Thread | None = None
        self._observer_thread: threading.Thread | None = None
        self._publisher_thread: threading.Thread | None = None
        self._pub_queue: queue.Queue[tuple[str, dict[str, Any]] | None] = queue.Queue()
        self._stop = threading.Event()
        self._started = False
        self._lock = threading.Lock()
        self._max_event_bytes = settings.max_event_bytes

    def update_max_event_bytes(self, max_event_bytes: int) -> None:
        with self._lock:
            self._max_event_bytes = max_event_bytes

    @property
    def max_event_bytes(self) -> int:
        with self._lock:
            return self._max_event_bytes

    @property
    def running(self) -> bool:
        return (
            self._started
            and self._proxy_thread is not None
            and self._proxy_thread.is_alive()
            and self._observer_thread is not None
            and self._observer_thread.is_alive()
            and self._publisher_thread is not None
            and self._publisher_thread.is_alive()
        )

    def start(self) -> None:
        self._ctx = zmq.Context()
        curve = self._settings.curve

        self._xsub = self._ctx.socket(zmq.XSUB)
        self._xpub = self._ctx.socket(zmq.XPUB)
        ephemeral_public, ephemeral_secret = zmq.curve_keypair()

        if curve.enabled:
            server_public, server_secret = self._load_server_keys()
            for sock in (self._xsub, self._xpub):
                sock.curve_secretkey = server_secret
                sock.curve_publickey = server_public
                sock.curve_server = True

            self._authenticator = ThreadAuthenticator(self._ctx)
            self._authenticator.start()
            self._authenticator.allow("127.0.0.1")
            # Merge the externally configured allowlist (if any) with our own first-party ephemeral
            # key so internal connectors always work regardless of the external allowlist contents.
            self._curve_tempdir = tempfile.TemporaryDirectory(prefix="opal-event-curve-")
            if curve.authorized_client_keys_file:
                for name in os.listdir(curve.authorized_client_keys_file):
                    if name.endswith(".key"):
                        shutil.copy(
                            os.path.join(curve.authorized_client_keys_file, name),
                            os.path.join(self._curve_tempdir.name, name),
                        )
            _write_public_cert(os.path.join(self._curve_tempdir.name, "_internal.key"), ephemeral_public)
            self._authenticator.configure_curve(domain="*", location=self._curve_tempdir.name)

        self._xsub.bind(self._settings.publishers)
        self._xpub.bind(self._settings.subscribers)

        self._observer_sub = self._make_client_socket(zmq.SUB, curve, ephemeral_public, ephemeral_secret)
        self._observer_sub.setsockopt(zmq.SUBSCRIBE, b"")
        self._observer_sub.connect(self._settings.subscribers)

        self._stop.clear()
        self._proxy_thread = threading.Thread(target=self._run_proxy, name="opal-event-zmq-proxy", daemon=True)
        self._observer_thread = threading.Thread(target=self._run_observer, name="opal-event-zmq-observer", daemon=True)
        self._publisher_thread = threading.Thread(
            target=self._run_publisher,
            args=(curve, ephemeral_public, ephemeral_secret),
            name="opal-event-zmq-publisher",
            daemon=True,
        )
        self._proxy_thread.start()
        self._observer_thread.start()
        self._publisher_thread.start()
        self._started = True
        time.sleep(0.2)  # mitigate PUB/SUB slow-joiner before the service reports readiness

    def _make_client_socket(self, kind: int, curve, ephemeral_public: bytes, ephemeral_secret: bytes) -> zmq.Socket:
        sock = self._ctx.socket(kind)
        if curve.enabled:
            server_public, _ = self._load_server_keys()
            sock.curve_secretkey = ephemeral_secret
            sock.curve_publickey = ephemeral_public
            sock.curve_serverkey = server_public
        return sock

    def _load_server_keys(self) -> tuple[bytes, bytes]:
        curve = self._settings.curve
        if not curve.server_public_key_file or not curve.server_secret_key_file:
            raise RuntimeError("CURVE enabled but server key files are not configured")
        public, _ = zmq.auth.load_certificate(curve.server_public_key_file)
        _, secret = zmq.auth.load_certificate(curve.server_secret_key_file)
        return public, secret

    def _run_proxy(self) -> None:
        with contextlib.suppress(zmq.ZMQError):  # expected on context termination during stop()
            zmq.proxy(self._xsub, self._xpub)

    def _run_observer(self) -> None:
        poller = zmq.Poller()
        poller.register(self._observer_sub, zmq.POLLIN)
        while not self._stop.is_set():
            try:
                events = dict(poller.poll(timeout=200))
            except zmq.ZMQError:
                break  # socket closed during stop()
            if self._observer_sub not in events:
                continue
            try:
                frames = self._observer_sub.recv_multipart(flags=zmq.NOBLOCK)
            except zmq.Again:
                continue
            except zmq.ZMQError:
                break
            if len(frames) != 2:
                message = f"expected exactly 2 frames, received {len(frames)}"
                logger.warning("rejected invalid event on observer path: %s", message)
                self._on_event({"_invalid": True, "error": message})
                continue
            topic_bytes, payload_bytes = frames
            try:
                normalized = parse_and_normalize(topic_bytes, payload_bytes, self.max_event_bytes)
            except InvalidEventError as exc:
                logger.warning("rejected invalid event on observer path: %s", exc)
                self._on_event({"_invalid": True, "error": str(exc)})
                continue
            try:
                self._on_event(normalized)
            except Exception:
                logger.exception("on_event handler raised for topic %s", normalized.get("topic"))

    def _run_publisher(self, curve, ephemeral_public: bytes, ephemeral_secret: bytes) -> None:
        pub_sock = self._make_client_socket(zmq.PUB, curve, ephemeral_public, ephemeral_secret)
        pub_sock.connect(self._settings.publishers)
        try:
            while not self._stop.is_set():
                try:
                    item = self._pub_queue.get(timeout=0.1)
                except queue.Empty:
                    continue
                if item is None:
                    break
                topic, envelope = item
                try:
                    pub_sock.send_multipart([topic.encode("utf-8"), json.dumps(envelope).encode("utf-8")])
                except zmq.ZMQError:
                    break
        finally:
            pub_sock.close(linger=0)

    def publish(self, topic: str, envelope: dict[str, Any]) -> None:
        if not self._started or self._stop.is_set():
            raise RuntimeError("broker is not started")
        self._pub_queue.put((topic, envelope))

    def stop(self) -> None:
        self._stop.set()
        self._pub_queue.put(None)
        if self._publisher_thread is not None:
            self._publisher_thread.join(timeout=2)
        for sock in (self._xsub, self._xpub, self._observer_sub):
            if sock is not None:
                sock.close(linger=0)
        if self._authenticator is not None:
            self._authenticator.stop()
        if self._curve_tempdir is not None:
            self._curve_tempdir.cleanup()
        if self._proxy_thread is not None:
            self._proxy_thread.join(timeout=2)
        if self._observer_thread is not None:
            self._observer_thread.join(timeout=2)
        if self._ctx is not None:
            self._ctx.term()
        self._started = False
